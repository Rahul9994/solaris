const W = 1024;
const H = 512;
const px = (lon: number) => ((lon + 180) / 360) * W;
const py = (lat: number) => ((90 - lat) / 180) * H;

function layer(draw: (ctx: CanvasRenderingContext2D) => void, blur: number): Uint8ClampedArray {
  const c = document.createElement('canvas');
  c.width = W;
  c.height = H;
  const ctx = c.getContext('2d')!;
  ctx.fillStyle = '#000';
  ctx.fillRect(0, 0, W, H);
  ctx.filter = blur > 0 ? `blur(${blur}px)` : 'none';
  draw(ctx);
  return ctx.getImageData(0, 0, W, H).data;
}

function polyPath(ctx: CanvasRenderingContext2D, p: Poly, off: number) {
  ctx.beginPath();
  for (let i = 0; i < p.length; i += 2) {
    const x = px(p[i] + off);
    const y = py(p[i + 1]);
    if (i === 0) ctx.moveTo(x, y);
    else ctx.lineTo(x, y);
  }
  ctx.closePath();
}

function fillPolys(ctx: CanvasRenderingContext2D, polys: Poly[], color: string) {
  ctx.fillStyle = color;
  for (const p of polys) for (const off of [-360, 0, 360]) {
    polyPath(ctx, p, off);
    ctx.fill();
  }
}

function weighted(ctx: CanvasRenderingContext2D, list: [number, Poly][]) {
  for (const [w, p] of list) {
    const g = Math.round(w * 255);
    fillPolys(ctx, [p], `rgb(${g},${g},${g})`);
  }
}

/** Builds two RGB textures: A = (land, city lights, mountains), B = (desert, forest, ice) */
export function buildEarthMaps() {
  const land = layer((ctx) => {
    fillPolys(ctx, LAND, '#fff');
    fillPolys(ctx, WATER, '#000');
  }, 1.6);
  const cities = layer((ctx) => {
    ctx.globalCompositeOperation = 'lighter';
    for (let i = 0; i < CITIES.length; i += 4) {
      const [lon, lat, r, k] = [CITIES[i], CITIES[i + 1], CITIES[i + 2], CITIES[i + 3]];
      const rx = (r / 360) * W * 1.6;
      for (const off of [-360, 0, 360]) {
        const x = px(lon + off);
        const y = py(lat);
        const g = ctx.createRadialGradient(x, y, 0, x, y, rx);
        g.addColorStop(0, `rgba(255,255,255,${k})`);
        g.addColorStop(1, 'rgba(255,255,255,0)');
        ctx.fillStyle = g;
        ctx.fillRect(x - rx, y - rx, rx * 2, rx * 2);
      }
    }
  }, 0);
  const mountains = layer((ctx) => {
    ctx.strokeStyle = '#fff';
    ctx.lineCap = 'round';
    ctx.lineJoin = 'round';
    for (const [w, pts] of MOUNTAINS) {
      ctx.lineWidth = (w / 360) * W;
      for (const off of [-360, 0, 360]) {
        ctx.beginPath();
        for (let i = 0; i < pts.length; i += 2) {
          const x = px(pts[i] + off);
          const y = py(pts[i + 1]);
          if (i === 0) ctx.moveTo(x, y);
          else ctx.lineTo(x, y);
        }
        ctx.stroke();
      }
    }
  }, 5);
  const desert = layer((ctx) => weighted(ctx, DESERT), 7);
  const forest = layer((ctx) => weighted(ctx, FOREST), 8);
  const ice = layer((ctx) => fillPolys(ctx, ICE, '#fff'), 3);

  const make = (r: Uint8ClampedArray, g: Uint8ClampedArray, b: Uint8ClampedArray) => {
    const c = document.createElement('canvas');
    c.width = W;
    c.height = H;
    const ctx = c.getContext('2d')!;
    const img = ctx.createImageData(W, H);
    for (let i = 0; i < W * H * 4; i += 4) {
      img.data[i] = r[i];
      img.data[i + 1] = g[i];
      img.data[i + 2] = b[i];
      img.data[i + 3] = 255;
    }
    ctx.putImageData(img, 0, 0);
    const t = new CanvasTexture(c);
    t.colorSpace = NoColorSpace;
    t.wrapS = RepeatWrapping;
    t.minFilter = LinearFilter;
    t.magFilter = LinearFilter;
    t.generateMipmaps = false;
    t.needsUpdate = true;
    return t;
  };

  return { a: make(land, cities, mountains), b: make(desert, forest, ice) };
}
